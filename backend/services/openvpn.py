def load_openvpn():

    data = load_running(OPENVPN_SETTINGS, {})

    server = dict(DEFAULT_SERVER)
    server.update(load_defaults(OPENVPN_SETTINGS).get("server", {}))
    server.update(data.get("server", {}))

    return {
        "server": server,
        "clients": data.get("clients", [])
    }


def save_openvpn(data, confirm=None, apply=True):
    """
    Applies the data through safe apply; returns a result dict.
    """

    return transaction.change(
        OPENVPN_SETTINGS, data, confirm=confirm, apply=apply
    )


def validate_server(server):

    try:
        port = int(server.get("port"))
    except (TypeError, ValueError):
        return False, "Invalid port."

    if not 1 <= port <= 65535:
        return False, "Invalid port."

    proto = server.get("proto")

    if proto not in ("udp", "tcp"):
        return False, "Protocol must be UDP or TCP."

    try:
        network = ipaddress.IPv4Network(str(server.get("network")), strict=True)
    except ValueError:
        return False, "Invalid tunnel network. Use CIDR, e.g. 10.9.0.0/24."

    if not 16 <= network.prefixlen <= 29:
        return False, "Tunnel network must be between /16 and /29."

    for lan in get_lan_networks():

        if network.overlaps(ipaddress.IPv4Network(lan)):
            return False, f"Tunnel network overlaps the LAN ({lan})."

    endpoint = str(server.get("endpoint") or "").strip()

    if endpoint and not all(
        c.isalnum() or c in ".-" for c in endpoint
    ):
        return False, "Invalid public address. Use a hostname or IP."

    dns = [d.strip() for d in str(server.get("dns") or "").split(",") if d.strip()]

    for entry in dns:
        try:
            ipaddress.IPv4Address(entry)
        except ValueError:
            return False, f"Invalid DNS server: {entry}"

    if server.get("routing") not in ("full", "lan"):
        return False, "Invalid routing mode."

    return True, {
        "enabled": server.get("enabled") is True,
        "port": port,
        "proto": proto,
        "network": str(network),
        "endpoint": endpoint,
        "dns": ", ".join(dns),
        "routing": server["routing"]
    }


