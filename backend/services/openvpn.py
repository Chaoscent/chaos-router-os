def has_openvpn():

    return which("openvpn") is not None


def get_easyrsa():

    found = which("easyrsa")

    if found:
        return found

    for path in EASYRSA_PATHS:

        if os.path.exists(path):
            return path

    return None


def easyrsa(*args):

    path = get_easyrsa()

    if not path:
        return False, "easy-rsa is not available."

    return run_command(privileged([
        path,
        "--batch",
        f"--pki-dir={PKI_DIR}",
        *args
    ]))


def root_file_exists(path):

    ok, _ = run_command(privileged(["test", "-f", path]))

    return ok


def ensure_nat_script():

    return write_root_file(NAT_SCRIPT, NAT_SCRIPT_CONTENT, mode="755")


