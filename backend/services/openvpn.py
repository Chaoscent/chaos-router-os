def apply_server():
    """
    Applies the running OpenVPN server config.
    """

    server = load_openvpn()["server"]

    if not has_openvpn():

        if not server["enabled"]:
            return True, "OpenVPN server stopped."

        return False, "OpenVPN is not available."

    if not server["enabled"]:

        stop_unit(SERVER_UNIT)

        return True, sync_firewall("openvpn", []) or "OpenVPN server stopped."

    for step in (init_pki, refresh_crl, ensure_nat_script):

        ok, result = step()

        if not ok:
            return False, f"OpenVPN could not be prepared: {result}"

    ok, result = write_root_file(
        SERVER_CONF,
        render_server_config(server)
    )

    if not ok:
        return False, f"OpenVPN config could not be written: {result}"

    warning = sync_firewall("openvpn", server_firewall_rules(server))

    ok, result = start_unit(SERVER_UNIT)

    if not ok:
        return False, f"OpenVPN failed to start: {result}"

    return True, warning or "OpenVPN server running."


def verify_server():

    if not load_openvpn()["server"]["enabled"]:
        return True, "OK"

    return unit_stays_active(SERVER_UNIT)


def save_server(settings):
    """
    Validates server settings and applies them through safe apply.
    """

    data = load_openvpn()

    merged = dict(data["server"])
    merged.update(settings or {})

    ok, result = validate_server(merged)

    if not ok:
        return transaction.result(False, result)

    data["server"] = result

    return save_openvpn(data)


