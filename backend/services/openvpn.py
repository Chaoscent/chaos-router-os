# PKI
# -------------------------------------------------------------------

def snapshot_pki():
    """
    Saves every file of the PKI (and the tls-crypt key) as JSON.
    """

    ok, output = run_command(privileged([
        "find",
        PKI_DIR,
        "-mindepth",
        "1",
        "-printf",
        "%y %P\\n"
    ]))

    if not ok:
        return False, f"Could not read the PKI: {output}"

    snapshot = {
        "version": 1,
        "dirs": [],
        "files": {},
        "tls_crypt_key": ""
    }

    for line in output.splitlines():

        kind, _, relative = line.partition(" ")

        if kind == "d":
            snapshot["dirs"].append(relative)
            continue

        if kind != "f":
            continue

        ok, content = read_root_file(f"{PKI_DIR}/{relative}")

        # easy-rsa only writes text files; skip anything else.
        if ok:
            snapshot["files"][relative] = content

    if "ca.crt" not in snapshot["files"]:
        return False, "The PKI has no CA certificate."

    ok, key = read_root_file(TLS_CRYPT_KEY)

    if ok:
        snapshot["tls_crypt_key"] = key

    # Holds the CA private key.
    save_system(PKI_SNAPSHOT, snapshot, secret=True)

    return True, "OK"


def restore_pki():
    """
    Recreates PKI_DIR from the JSON snapshot.
    """

    snapshot = load_system(PKI_SNAPSHOT, {})

    if not snapshot.get("files", {}).get("ca.crt"):
        return False

    for directory in [""] + snapshot.get("dirs", []):

        run_command(privileged([
            "install",
            "-d",
            "-m",
            "700",
            f"{PKI_DIR}/{directory}".rstrip("/")
        ]))

    for relative, content in snapshot["files"].items():

        ok, _ = write_root_file(f"{PKI_DIR}/{relative}", content)

        if not ok:
            return False

    if snapshot.get("tls_crypt_key"):
        write_root_file(TLS_CRYPT_KEY, snapshot["tls_crypt_key"])

    return True


def pki_ready():

    if root_file_exists(f"{PKI_DIR}/ca.crt"):
        return True

    return restore_pki() and root_file_exists(f"{PKI_DIR}/ca.crt")


def init_pki():
    """
    Creates the CA, the server certificate, a CRL and the
    tls-crypt key. Safe to call again; existing PKI is kept.
    """

    if pki_ready():
        return True, "OK"

    steps = [
        ("init-pki",),
        # EC keys are small and fast to generate on the Pi.
        ("--use-algo=ec", "--curve=prime256v1",
         "--req-cn=Chaos Router OS CA", "build-ca", "nopass"),
        ("--use-algo=ec", "--curve=prime256v1",
         "build-server-full", "server", "nopass")
    ]

    for step in steps:

        ok, result = easyrsa(*step)

        if not ok:
            return False, f"Certificate setup failed ({step[-2]}): {result}"

    ok, result = run_command(privileged([
        which("openvpn"),
        "--genkey",
        "secret",
        TLS_CRYPT_KEY
    ]))

    if not ok:
        return False, f"Could not create tls-crypt key: {result}"

    return refresh_crl()


def refresh_crl():
    """
    Regenerates the CRL (it expires) and publishes a copy
    readable after OpenVPN drops privileges.
    """

    ok, result = easyrsa("gen-crl")

    if not ok:
        return False, f"Could not generate CRL: {result}"

    ok, crl = read_root_file(f"{PKI_DIR}/crl.pem")

    if not ok:
        return False, crl

    ok, result = write_root_file(PUBLIC_CRL, crl, mode="644")

    if not ok:
        return False, result

    return snapshot_pki()


def read_pem(path):
    """
    Reads a PEM file, dropping easy-rsa's text dump before it.
    """

    ok, content = read_root_file(path)

    if not ok:
        return None

    start = content.find("-----BEGIN")

    return content[start:].strip() if start >= 0 else content.strip()


