def add_client(name):

    data = load_openvpn()

    name = str(name or "").strip()

    if not valid_name(name) or name == "server":
        return False, "Name must be 1-32 letters, numbers, - or _."

    if any(c["name"] == name for c in data["clients"]):
        return False, f"A client named {name} already exists."

    if not has_openvpn():
        return False, "OpenVPN is not available."

    ok, result = init_pki()

    if not ok:
        return False, result

    ok, result = easyrsa(
        "--use-algo=ec",
        "--curve=prime256v1",
        "build-client-full",
        name,
        "nopass"
    )

    if not ok:
        return False, f"Could not create certificate: {result}"

    ok, result = snapshot_pki()

    if not ok:
        return False, f"Certificate created, but not backed up: {result}"

    data["clients"].append({
        "name": name,
        "created": int(time.time())
    })

    # The certificate exists now; record it without restarting the
    # server, which would drop every connected device.
    outcome = save_openvpn(data, apply=False)

    return outcome["success"], (
        "Client added." if outcome["success"] else outcome["message"]
    )


def revoke_client(name):

    data = load_openvpn()

    if not any(c["name"] == name for c in data["clients"]):
        return False, "Client not found."

    ok, result = easyrsa("revoke", name)

    if not ok:
        return False, f"Could not revoke certificate: {result}"

    ok, result = refresh_crl()

    if not ok:
        return False, result

    data["clients"] = [c for c in data["clients"] if c["name"] != name]

    # The CRL is checked on connect; re-applying restarts the server
    # and drops the revoked device's live session.
    outcome = save_openvpn(data, confirm=False)

    return outcome["success"], (
        "Client revoked." if outcome["success"] else outcome["message"]
    )


def get_client_config(name):
    """
    Returns (ok, filename or message, config text).
    """

    data = load_openvpn()

    if not any(c["name"] == name for c in data["clients"]):
        return False, "Client not found.", None

    config = render_client_config(data["server"], name)

    if not config:
        return False, "Could not read the client's certificates.", None

    return True, f"{name}.ovpn", config


