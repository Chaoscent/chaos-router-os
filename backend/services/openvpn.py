def render_server_config(server):

    network = ipaddress.IPv4Network(server["network"])

    lines = [
        "# Generated by Chaos Router OS. Do not edit by hand.",
        "# Changes are overwritten from the VPN page.",
        "",
        f"port {server['port']}",
        f"proto {server['proto']}",
        f"dev {SERVER_DEVICE}",
        "dev-type tun",
        "topology subnet",
        f"server {network.network_address} {network.netmask}",
        "",
        f"ca {PKI_DIR}/ca.crt",
        f"cert {PKI_DIR}/issued/server.crt",
        f"key {PKI_DIR}/private/server.key",
        "dh none",
        f"tls-crypt {TLS_CRYPT_KEY}",
        f"crl-verify {PUBLIC_CRL}",
        f"data-ciphers {CIPHERS}",
        "",
        "keepalive 10 120",
        "persist-key",
        "persist-tun",
        "user nobody",
        "group nogroup"
    ]

    if server["proto"] == "udp":
        lines.append("explicit-exit-notify 1")

    lines.append("")

    if server["routing"] == "full":
        lines.append('push "redirect-gateway def1 bypass-dhcp"')
    else:
        for lan in get_lan_networks():
            lan_net = ipaddress.IPv4Network(lan)
            lines.append(
                f'push "route {lan_net.network_address} {lan_net.netmask}"'
            )

    for entry in [d.strip() for d in server["dns"].split(",") if d.strip()]:
        lines.append(f'push "dhcp-option DNS {entry}"')

    lines += [
        "",
        "# NAT so clients reach the internet through the router.",
        "script-security 2",
        f"setenv CHAOS_NAT_SOURCE {network}",
        f"setenv CHAOS_WAN {get_wan_interface()}",
        f"up {NAT_SCRIPT}",
        f"down {NAT_SCRIPT}",
        "",
        "verb 3"
    ]

    return "\n".join(lines) + "\n"


def render_client_config(server, name):

    ca = read_pem(f"{PKI_DIR}/ca.crt")
    cert = read_pem(f"{PKI_DIR}/issued/{name}.crt")
    key = read_pem(f"{PKI_DIR}/private/{name}.key")
    tls = read_pem(TLS_CRYPT_KEY)

    if not all((ca, cert, key, tls)):
        return None

    endpoint = server["endpoint"] or "YOUR_PUBLIC_ADDRESS"

    lines = [
        f"# {name} - generated by Chaos Router OS",
        "client",
        "dev tun",
        f"proto {server['proto']}",
        f"remote {endpoint} {server['port']}",
        "resolv-retry infinite",
        "nobind",
        "persist-key",
        "persist-tun",
        "remote-cert-tls server",
        f"data-ciphers {CIPHERS}",
        "verb 3",
        "",
        "<ca>", ca, "</ca>",
        "<cert>", cert, "</cert>",
        "<key>", key, "</key>",
        "<tls-crypt>", tls, "</tls-crypt>"
    ]

    return "\n".join(lines) + "\n"


def server_firewall_rules(server):

    return firewall_rules_for("OpenVPN", [
        ["allow", "in", "from", "any", "to", "any",
         "port", str(server["port"]), "proto", server["proto"]],
        ["allow", "in", "on", SERVER_DEVICE],
        ["route", "allow", "in", "on", SERVER_DEVICE]
    ])


