def get_connected_clients():
    """
    Parses the status file (version 2, comma separated).
    """

    ok, content = read_root_file(STATUS_FILE)

    if not ok:
        return {}

    header = None
    clients = {}

    for row in csv.reader(io.StringIO(content)):

        if not row:
            continue

        if row[0] == "HEADER" and row[1:2] == ["CLIENT_LIST"]:
            header = row[2:]
            continue

        if row[0] != "CLIENT_LIST" or not header:
            continue

        entry = dict(zip(header, row[1:]))

        try:

            clients[entry.get("Common Name", "")] = {
                "real_address": entry.get("Real Address", ""),
                "virtual_address": entry.get("Virtual Address", ""),
                "rx_bytes": int(entry.get("Bytes Received", 0)),
                "tx_bytes": int(entry.get("Bytes Sent", 0)),
                "connected_since": int(entry.get("Connected Since (time_t)", 0))
            }

        except ValueError:
            pass

    return clients


def get_openvpn_status():

    data = load_openvpn()

    installed = has_openvpn()
    running = installed and unit_active(SERVER_UNIT)

    live = get_connected_clients() if running else {}

    clients = []

    for client in data["clients"]:

        info = live.get(client["name"])

        clients.append({
            "name": client["name"],
            "created": client.get("created"),
            "connected": info is not None,
            **(info or {})
        })

    return {
        "installed": installed,
        "easyrsa": get_easyrsa() is not None,
        "running": running,
        "server": data["server"],
        "clients": clients
    }
