# openvpn.json: server defaults in /etc/chaos-router-os,
# settings, keys and clients in /var/lib/chaos-router-os.
OPENVPN_SETTINGS = "openvpn"

SERVER_NAME = "chaos"
SERVER_DIR = "/etc/openvpn/server"
SERVER_CONF = f"{SERVER_DIR}/{SERVER_NAME}.conf"
SERVER_UNIT = f"openvpn-server@{SERVER_NAME}"
SERVER_DEVICE = "ovpns0"

# Written by Debian's openvpn-server@.service (--status-version 2).
STATUS_FILE = f"/run/openvpn-server/status-{SERVER_NAME}.log"

# easy-rsa's working directory (PEM files, index, serial).
PKI_DIR = f"{SERVER_DIR}/chaos-pki"
TLS_CRYPT_KEY = f"{SERVER_DIR}/chaos-tls-crypt.key"

# The CA cannot be regenerated, so after every change the whole PKI
# is snapshotted as JSON to /var/lib/chaos-router-os/system/
# openvpn_pki.json and restored from there when PKI_DIR is missing.
# Issued certificates exist the moment they are created, so this is a
# system record, never reverted with the config.
PKI_SNAPSHOT = "openvpn_pki"

# OpenVPN drops to nobody, which must still read the CRL.
PUBLIC_CRL = f"{SERVER_DIR}/chaos-crl.pem"

# Shared up/down hook that adds NAT for VPN traffic.
NAT_SCRIPT = "/etc/openvpn/chaos-nat.sh"

EASYRSA_PATHS = (
    "/usr/share/easy-rsa/easyrsa",
)

CIPHERS = "AES-256-GCM:AES-128-GCM:CHACHA20-POLY1305"

DEFAULT_SERVER = {
    "enabled": False,
    "port": 1194,
    "proto": "udp",
    "network": "10.9.0.0/24",
    "endpoint": "",
    "dns": "1.1.1.1",
    "routing": "full"
}

NAT_SCRIPT_CONTENT = """#!/bin/sh
# Generated by Chaos Router OS. Do not edit by hand.
# OpenVPN up/down hook: NAT for VPN traffic.
#   Server: CHAOS_NAT_SOURCE / CHAOS_WAN set via setenv.
#   Client: masquerade LAN traffic leaving through the tunnel ($dev).

if [ -n "$CHAOS_NAT_SOURCE" ]; then
    RULE="-s $CHAOS_NAT_SOURCE -o $CHAOS_WAN -j MASQUERADE"
else
    RULE="-o $dev -j MASQUERADE"
fi

case "$script_type" in
    up)
        iptables -t nat -C POSTROUTING $RULE 2>/dev/null ||
            iptables -t nat -A POSTROUTING $RULE
        ;;
    down)
        iptables -t nat -D POSTROUTING $RULE 2>/dev/null
        ;;
esac

exit 0
"""


