def normalize(data):
    """
    {"country", "networks"} from stored settings, in the current or
    the old single-network format.
    """

    data = data if isinstance(data, dict) else {}

    networks = data.get("networks")

    if isinstance(networks, dict):
        networks = {
            name: {**DEFAULT_NETWORK, **{k: v for k, v in net.items() if k in NETWORK_FIELDS}}
            for name, net in networks.items()
            if isinstance(net, dict) and INTERFACE_RE.fullmatch(str(name))
        }
    elif data.get("interface"):
        # Old format: one network, flat.
        networks = {
            str(data["interface"]): {
                **DEFAULT_NETWORK,
                **{k: data[k] for k in NETWORK_FIELDS if k in data}
            }
        }
    else:
        networks = {}

    return {
        "country": str(data.get("country") or "").upper(),
        "networks": networks
    }


def get_wifi_settings():

    # Each layer on its own: the two formats cannot be merged key by key.
    defaults = normalize(load_defaults(WIFI_SETTINGS, DEFAULT_SETTINGS))

    running = load_running(WIFI_SETTINGS, None)

    if not isinstance(running, dict):
        return defaults

    settings = normalize(running)

    settings["country"] = settings["country"] or defaults["country"]

    return settings


def off_settings():
    """
    Every access point off (factory reset, uninstall); the country stays.
    """

    return {"country": get_wifi_settings()["country"], "networks": {}}


def suggest_address(interface, settings):
    """
    A free subnet for a radio without settings: 10.42.0.1/24 for the
    first, then 10.43.0.1/24, ...
    """

    used = set()

    for name, net in settings["networks"].items():

        if name == interface:
            continue

        try:
            used.add(ipaddress.IPv4Interface(f"{net['address']}/{net['prefix']}").network)
        except ValueError:
            pass

    for second in range(42, 255):

        network = ipaddress.IPv4Network(f"10.{second}.0.0/24")

        if not any(network.overlaps(u) for u in used):
            return f"10.{second}.0.1", 24

    return DEFAULT_NETWORK["address"], DEFAULT_NETWORK["prefix"]


def get_network(interface, settings=None):
    """
    One radio's network, flat as the WiFi page edits it:
    {"interface", "country", "enabled", "ssid", ...}. A radio without
    settings gets the defaults with a free subnet.
    """

    settings = settings or get_wifi_settings()

    net = settings["networks"].get(interface)

    if net is None:
        address, prefix = suggest_address(interface, settings)
        net = {**DEFAULT_NETWORK, "address": address, "prefix": prefix}

    return {**net, "interface": interface, "country": settings["country"]}


def get_networks(settings=None):
    """
    {interface: network} for every radio there is, and every radio
    with settings (e.g. an unplugged USB adapter).
    """

    settings = settings or get_wifi_settings()

    names = sorted(set(get_wireless_interfaces()) | set(settings["networks"]))

    return {name: get_network(name, settings) for name in names}


def enabled_networks(settings=None):
    """
    The networks that are on, as flat settings.
    """

    settings = settings or get_wifi_settings()

    return [
        get_network(name, settings)
        for name, net in sorted(settings["networks"].items())
        if net["enabled"]
    ]


def validate_network(data, settings=None):
    """
    Validates and normalises one radio's network (flat, with
    "interface" and "country").

    Returns (True, network) or (False, message).
    """

    data = data or {}
    settings = settings or get_wifi_settings()

    interface = str(data.get("interface") or "").strip()

    if not INTERFACE_RE.fullmatch(interface):
        return False, "Invalid interface."

    net = get_network(interface, settings)
    net.update(data)

    enabled = net.get("enabled") is True

    if enabled and interface not in get_wireless_interfaces():
        return False, f"{interface} is not a wireless interface."

    ssid = str(net.get("ssid") or "")

    if not ssid.strip():
        return False, "Network name cannot be empty."

    if len(ssid.encode("utf-8")) > 32:
        return False, "Network name is too long (max 32 bytes)."

    if any(ord(c) < 0x20 or ord(c) == 0x7f for c in ssid):
        return False, "Network name contains invalid characters."

    security = net.get("security")

    if security not in SECURITY_MODES:
        return False, "Invalid security mode."

    password = str(net.get("password") or "")

    if security != "open" and not PASSPHRASE_RE.fullmatch(password):
        return False, (
            "Password must be 8-63 characters "
            "(letters, numbers, symbols and spaces)."
        )

    band = str(net.get("band"))

    if band not in BANDS:
        return False, "Invalid band."

    try:
        channel = int(net.get("channel"))
    except (TypeError, ValueError):
        return False, "Invalid channel."

    if channel not in BANDS[band]["channels"]:
        return False, f"Channel {channel} is not available on {band} GHz."

    # 6 GHz only allows WPA3-SAE (open networks would need OWE).
    if band == "6" and security != "wpa3":
        return False, "6 GHz requires WPA3 Personal."

    if enabled:

        support = get_band_support(interface)

        if support is not None:

            if not support[band]:
                return False, f"{interface} does not support {band} GHz."

            if channel not in support[band]:
                return False, (
                    f"{interface} does not support channel "
                    f"{channel} on {band} GHz."
                )

    country = str(net.get("country") or "").strip().upper()

    if country and not COUNTRY_RE.fullmatch(country):
        return False, "Country must be a two-letter code, e.g. US or DE."

    if enabled and not country:
        return False, "Set the country first: it decides which channels are allowed."

    bridged = bridges_interface(interface)

    ok, result = validate_address(
        net.get("address"), net.get("prefix"), interface,
        check_overlap=enabled and not bridged,
        settings=settings
    )

    if not ok:
        return False, result

    address, prefix = result

    return True, {
        "interface": interface,
        "country": country,
        "enabled": enabled,
        "ssid": ssid,
        "password": password if security != "open" else "",
        "security": security,
        "band": band,
        "channel": channel,
        "hidden": net.get("hidden") is True,
        "isolate_clients": net.get("isolate_clients") is True,
        "address": address,
        "prefix": prefix
    }


def with_network(settings, network):
    """
    The whole Wi-Fi settings with one radio's network replaced.
    """

    return {
        "country": network["country"] or settings["country"],
        "networks": {
            **settings["networks"],
            network["interface"]: {k: network[k] for k in NETWORK_FIELDS}
        }
    }


def validate_wifi_settings(data):
    """
    Validates the whole Wi-Fi settings (e.g. from a backup), in the
    current or the old format. Returns (True, settings) or (False, message).
    """

    data = normalize(data)

    result = {"country": data["country"], "networks": {}}

    for name, net in sorted(data["networks"].items()):

        # Radios that are not here now (USB adapter) are kept as they
        # are, switched off.
        if name not in get_wireless_interfaces():
            result["networks"][name] = {**net, "enabled": False}
            continue

        ok, checked = validate_network(
            {**net, "interface": name, "country": data["country"]},
            settings=result
        )

        if not ok:
            return False, f"{name}: {checked}"

        result = with_network(result, checked)

    return True, result


def get_other_networks(interface, settings=None):
    """
    [(name, IPv4Network)] the access point's subnet must not overlap:
    every IPv4 address on other interfaces, and the subnets of the
    other radios' networks that are on.
    """

    networks = []

    applied = applied_addresses()

    for line in (run(["ip", "-4", "-o", "addr", "show"]) or "").splitlines():

        parts = line.split()

        if len(parts) < 4 or parts[2] != "inet":
            continue

        name = parts[1]

        # Its own address is replaced anyway.
        if name in ("lo", interface):
            continue

        try:
            networks.append((name, ipaddress.IPv4Interface(parts[3]).network))
        except ValueError:
            pass

    settings = settings or get_wifi_settings()

    for name, net in settings["networks"].items():

        if name == interface or not net["enabled"] or name in applied:
            continue

        if bridges_interface(name):
            continue

        try:
            networks.append((name, ipaddress.IPv4Interface(f"{net['address']}/{net['prefix']}").network))
        except ValueError:
            pass

    return networks


def validate_address(address, prefix, interface, check_overlap=True, settings=None):
    """
    Returns (True, (address, prefix)) or (False, message).
    """

    try:
        ip = ipaddress.IPv4Address(str(address or "").strip())
    except ValueError:
        return False, "Invalid router address."

    try:
        prefix = int(prefix)
    except (TypeError, ValueError):
        return False, "Invalid prefix (CIDR), e.g. 24."

    if not 8 <= prefix <= 30:
        return False, "The prefix (CIDR) must be between 8 and 30."

    network = ipaddress.IPv4Interface(f"{ip}/{prefix}").network

    if ip in (network.network_address, network.broadcast_address):
        return False, f"{ip} is the network or broadcast address of {network}."

    if check_overlap:

        for name, other in get_other_networks(interface, settings):

            if network.overlaps(other):
                return False, (
                    f"{network} overlaps {other} on {name}. "
                    f"Choose another subnet, e.g. {suggest_address(interface, settings or get_wifi_settings())[0]}/24."
                )

    return True, (str(ip), prefix)


