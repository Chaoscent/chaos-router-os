def save_wifi_settings(data):
    """
    Validates one radio's network, then applies all of them through
    safe apply. Returns a transaction result dict with the networks.
    """

    settings = get_wifi_settings()

    ok, result = validate_network(data, settings)

    if not ok:
        return transaction.result(False, result)

    outcome = transaction.change(WIFI_SETTINGS, with_network(settings, result))

    if outcome["success"] and result["enabled"] and not bridges_interface(result["interface"]):

        # DHCP follows the access point: its radio is served in the
        # new subnet (and confirmed or reverted together with it).
        from services import dhcp

        follow = dhcp.follow_wifi(result["interface"], result["address"], result["prefix"])

        if follow and not follow["success"]:
            outcome["message"] += f" DHCP on {result['interface']}: {follow['message']}"
        elif follow:
            outcome["message"] += f" DHCP now serves {result['interface']}."
            outcome["pending"] = follow.get("pending") or outcome.get("pending")

    outcome["networks"] = get_networks()

    return outcome


def running_instances():
    """
    Interfaces with an access point unit loaded, e.g. ["wlan0"].
    """

    output = run([
        "systemctl", "list-units", "--all", "--plain", "--no-legend",
        "chaos-hostapd@*"
    ]) or ""

    names = []

    for line in output.splitlines():

        unit = line.split()[0] if line.split() else ""

        if unit.startswith("chaos-hostapd@") and unit.endswith(".service"):
            names.append(unit[len("chaos-hostapd@"):-len(".service")])

    return names


def is_legacy_config():

    try:
        with open(LEGACY_CONF_FILE) as f:
            return f.readline().startswith(LEGACY_MARKER)
    except OSError:
        return False


def stop_legacy():
    """
    Moves off Debian's hostapd.service, which ran the one access point
    of older versions: it would fight over the radio.
    """

    if not is_legacy_config():
        return

    for cmd in (
        ["systemctl", "stop", "hostapd"],
        ["systemctl", "disable", "hostapd"],
        ["rm", "-f", LEGACY_CONF_FILE]
    ):
        run_command(privileged(cmd))


def apply_wifi_settings():
    """
    Applies the running Wi-Fi settings: an access point on every radio
    whose network is on, none on the others.
    """

    settings = get_wifi_settings()

    wanted = enabled_networks(settings)

    if not has_hostapd():

        if not wanted:
            return True, "Access points turned off."

        return False, "hostapd is not available."

    stop_legacy()

    present = set(get_wireless_interfaces())
    on = {net["interface"] for net in wanted if net["interface"] in present}

    # Off first: a radio's subnet may move to another one.
    for name in sorted(set(running_instances()) | set(applied_addresses()) | set(settings["networks"])):

        if name in on:
            continue

        ok, result = stop_access_point(name)

        if not ok:
            return False, result

    messages = []

    for net in wanted:

        # An unplugged USB adapter: its network starts when it is back
        # and the settings are applied again.
        if net["interface"] not in present:
            messages.append(f"{net['interface']} is not plugged in.")
            continue

        ok, result = start_access_point(net)

        if not ok:
            return False, f"{net['interface']}: {result}"

        if not result.endswith("unchanged."):
            messages.append(result)

    if messages:
        return True, " ".join(messages)

    return True, "Access points unchanged." if on else "Access points turned off."


def stop_access_point(interface):

    unit = unit_name(interface)

    if interface in running_instances():

        for cmd in (
            ["systemctl", "stop", unit],
            ["systemctl", "disable", unit]
        ):
            ok, result = run_command(privileged(cmd))

            if not ok:
                return False, f"The access point on {interface} could not be stopped: {result}"

    clear_address(interface)

    applied = load_running(APPLIED_CONFIGS, None) or {}

    if applied.pop(interface, None):
        save_running(APPLIED_CONFIGS, applied)

    if os.path.exists(config_path(interface)):
        run_command(privileged(["rm", "-f", config_path(interface)]))

    if interface in get_wireless_interfaces():
        set_networkmanager_managed(interface, True)

    return True, f"Access point on {interface} turned off."


def start_access_point(settings):
    """
    Starts the access point of one radio (flat settings with
    "interface" and "country") and gives the radio its address, or
    joins it to the LAN bridge. Also used for the setup Wi-Fi.
    """

    interface = settings["interface"]

    config = render_hostapd_config(settings)
    digest = hashlib.sha256(config.encode("utf-8")).hexdigest()

    applied = load_running(APPLIED_CONFIGS, None) or {}

    # Unchanged and running: its devices stay connected.
    if applied.get(interface) == digest and is_hostapd_running(interface) and (
        bridges_interface(interface)
        or has_address(interface, settings["address"], settings["prefix"])
    ):
        return True, f"Access point on {interface} unchanged."

    ok, result = install_hostapd_config(config, config_path(interface))

    if not ok:
        return False, f"Wi-Fi settings could not be applied: {result}"

    ok, result = set_networkmanager_managed(interface, False)

    if not ok:
        return False, (
            f"NetworkManager could not release {interface}: {result}"
        )

    commands = []

    # Raspberry Pi OS soft-blocks Wi-Fi until a country is set.
    if which("rfkill"):
        commands.append(["rfkill", "unblock", "wlan"])

    unit = unit_name(interface)

    commands += [
        ["systemctl", "enable", unit],
        ["systemctl", "restart", unit]
    ]

    for cmd in commands:

        ok, result = run_command(privileged(cmd))

        if not ok:

            if cmd[1] == "restart":
                result = get_hostapd_error(interface)

            return False, f"Wi-Fi settings could not be applied: {result}"

    applied[interface] = digest
    save_running(APPLIED_CONFIGS, applied)

    # Bridged: the access point is a port of br0 and has no address.
    if bridges_interface(interface):

        clear_address(interface)

        return True, f"Access point on {interface} applied (LAN bridge)."

    ok, result = set_address(interface, settings["address"], settings["prefix"])

    if not ok:
        return False, f"The address could not be set on {interface}: {result}"

    return True, f"Access point on {interface} applied, {settings['address']}/{settings['prefix']}."


def verify_wifi_settings():

    wanted = [
        net for net in enabled_networks()
        if net["interface"] in get_wireless_interfaces()
    ]

    if not wanted:
        return True, "OK"

    # hostapd gives up shortly after a "successful" start.
    time.sleep(SETTLE_SECONDS)

    for net in wanted:

        interface = net["interface"]

        if not is_hostapd_running(interface):
            return False, f"The access point on {interface} stopped right after starting. {get_hostapd_error(interface)}"

        if not bridges_interface(interface) and not has_address(interface, net["address"], net["prefix"]):
            return False, f"{net['address']}/{net['prefix']} is not set on {interface}."

    return True, "OK"


def ip_command(*args):

    return run_command(privileged(["ip", *args]))


def applied_addresses():
    """
    {interface: "address/prefix"} set by the access points.
    """

    applied = load_running(APPLIED_ADDRESS, None) or {}

    # Older format: one access point.
    if "interface" in applied:
        return {applied["interface"]: applied.get("address")} if applied["interface"] else {}

    return {k: v for k, v in applied.items() if isinstance(v, str)}


def clear_address(interface):
    """
    Removes the address an access point set on this interface.
    """

    applied = applied_addresses()

    if interface in applied:
        ip_command("-4", "addr", "flush", "dev", interface)
        del applied[interface]
        save_running(APPLIED_ADDRESS, applied)


def set_address(interface, address, prefix):
    """
    The equivalent of `ip addr add 10.42.0.1/24 dev wlan1`, replacing
    whatever IPv4 address the interface had.
    """

    ok, result = ip_command("-4", "addr", "flush", "dev", interface)

    if not ok:
        return False, result

    ok, result = ip_command("addr", "add", f"{address}/{prefix}", "dev", interface)

    if not ok:
        return False, result

    applied = applied_addresses()
    applied[interface] = f"{address}/{prefix}"
    save_running(APPLIED_ADDRESS, applied)

    return True, "OK"


def has_address(interface, address, prefix):

    output = run(["ip", "-4", "-o", "addr", "show", "dev", interface]) or ""

    return f"inet {address}/{prefix} " in output + " "


