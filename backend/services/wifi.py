def get_wifi_clients(interface=None):
    """
    Clients of every access point (or of one), each with its
    "interface".
    """

    names = [interface] if interface else [n["interface"] for n in enabled_networks()]

    clients = []

    for name in names:
        clients += get_station_clients(name)

    return clients


def get_station_clients(interface):
    """
    Parses `iw dev <iface> station dump` and matches hostnames
    from the DHCP leases.
    """

    iw = which("iw")

    if not iw or interface not in get_wireless_interfaces():
        return []

    ok, output = run_command(privileged([
        iw,
        "dev",
        interface,
        "station",
        "dump"
    ]))

    if not ok or not output:
        return []

    leases = {
        lease["mac"]: lease
        for lease in get_dhcp_leases()
    }

    clients = []
    current = None

    for line in output.splitlines():

        if line.startswith("Station "):

            mac = line.split()[1].upper()
            lease = leases.get(mac, {})

            current = {
                "interface": interface,
                "mac": mac,
                "hostname": lease.get("hostname", ""),
                "ip": lease.get("ip", ""),
                "signal": None,
                "connected": None,
                "rx_bytes": 0,
                "tx_bytes": 0
            }

            clients.append(current)
            continue

        if not current or ":" not in line:
            continue

        key, value = line.strip().split(":", 1)
        value = value.strip()

        try:

            if key == "signal":
                current["signal"] = int(value.split()[0])
            elif key == "connected time":
                current["connected"] = int(value.split()[0])
            elif key == "rx bytes":
                current["rx_bytes"] = int(value)
            elif key == "tx bytes":
                current["tx_bytes"] = int(value)

        except (ValueError, IndexError):
            pass

    return clients


